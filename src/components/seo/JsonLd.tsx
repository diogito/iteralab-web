// Server component that serializes a JSON-LD graph to a <script> tag.
// Used by pages/layouts to emit structured data for search engines and AI answer engines.
export function JsonLd({
  data,
}: {
  data: Record<string, unknown> | Record<string, unknown>[];
}) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(data).replace(/</g, '\\u003c'),
      }}
    />
  );
}